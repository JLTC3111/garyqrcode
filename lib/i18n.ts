export function translate(locale: Locale, text: string, values: CopyValues = {}): string {
  let copy = locale === "vi" ? vietnamese[text] ?? text : text;
  if (locale === "vi" && copy === text) {
    const maximum = /^String must contain at most (\d+) character/.exec(text);
    if (maximum) copy = `Vui lòng nhập không quá ${maximum[1]} ký tự.`;
    else if (/^(Invalid input|Invalid enum value|Expected |Required$)/.test(text)) copy = "Vui lòng kiểm tra thông tin này.";
  }
  return copy.replace(/\{(\w+)\}/g, (match, key: string) => values[key] === undefined ? match : String(values[key]));
}
